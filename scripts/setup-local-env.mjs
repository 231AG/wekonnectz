#!/usr/bin/env node
// Creates local, gitignored env files for development and tests. Never prints secret values.
//   supabase/.env  — read by the Supabase CLI (auth hook URI + secret). Needed BEFORE `supabase start`.
//   .env.local     — read by Next.js. Filled with local Supabase keys when the stack is running.
// Existing values are kept, so secrets stay stable across runs.
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

function readEnv(path) {
  if (!existsSync(path)) return {};
  return Object.fromEntries(
    readFileSync(path, "utf8")
      .split("\n")
      .filter((line) => /^[A-Z0-9_]+=/.test(line))
      .map((line) => {
        const i = line.indexOf("=");
        return [line.slice(0, i), line.slice(i + 1).replace(/^"|"$/g, "")];
      }),
  );
}

function writeEnv(path, values, header) {
  const body = Object.entries(values)
    .map(([k, v]) => `${k}=${v}`)
    .join("\n");
  writeFileSync(path, `${header}\n${body}\n`, { mode: 0o600 });
}

const random = (bytes) =>
  randomBytes(bytes)
    .toString("base64")
    .replace(/[^A-Za-z0-9]/g, "")
    .slice(0, bytes);

// 1. supabase/.env — Standard Webhooks secret for the Send-SMS hook.
const sb = readEnv("supabase/.env");
sb.SEND_SMS_HOOK_SECRET ??= `v1,whsec_${randomBytes(32).toString("base64")}`;
sb.SEND_SMS_HOOK_URI ??= "http://host.docker.internal:3000/api/auth/hooks/send-sms";
writeEnv("supabase/.env", sb, "# LOCAL DEV ONLY — generated by scripts/setup-local-env.mjs. Never commit.");

// 2. .env.local — Next.js server and client config.
const local = readEnv(".env.local");
local.SEND_SMS_HOOK_SECRET = sb.SEND_SMS_HOOK_SECRET;
local.APP_COOKIE_SECRET ??= random(48);
local.CRON_SECRET ??= random(32);
local.SMS_PROVIDER ??= "fake";
local.DEV_GEO_COUNTRY ??= "LR";
// Card payments scaffold (Phase 7b): the fake processor, local only.
local.CARD_PAYMENTS_ENABLED ??= "1";
local.CARD_PROCESSOR ??= "fake";
local.FAKE_CARD_WEBHOOK_SECRET ??= random(48);

let status = null;
try {
  const out = execFileSync("pnpm", ["exec", "supabase", "status", "-o", "env"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  });
  status = Object.fromEntries(
    out
      .split("\n")
      .filter((l) => l.includes("="))
      .map((l) => {
        const i = l.indexOf("=");
        return [l.slice(0, i), l.slice(i + 1).replace(/^"|"$/g, "")];
      }),
  );
} catch {
  // Supabase not running yet; .env.local gets its Supabase keys on the next run.
}

if (status?.API_URL) {
  local.NEXT_PUBLIC_SUPABASE_URL = status.API_URL;
  local.NEXT_PUBLIC_SUPABASE_ANON_KEY = status.ANON_KEY;
  local.SUPABASE_SERVICE_ROLE_KEY = status.SERVICE_ROLE_KEY;
}

writeEnv(".env.local", local, "# LOCAL DEV ONLY — generated by scripts/setup-local-env.mjs. Never commit.");
console.log(
  `env:setup — wrote supabase/.env and .env.local${status?.API_URL ? " (with local Supabase keys)" : " (Supabase not running: run `pnpm db:start` then `pnpm env:setup` again)"}.`,
);
